L = D3Q19()
C, W, OPP = L.c.tolist(), L.w.tolist(), L.opposite.tolist()
WN = {1/3: "W0", 1/18: "W1", 1/36: "W2"}
def wname(w):
    return min(WN.items(), key=lambda kv: abs(kv[0] - w))[1]

def lin(coeffs, names):
    """Σ coeff·name with integer coefficients, skipping zeros."""
    out = []
    for k, nm in zip(coeffs, names):
        if k == 0:
            continue
        out.append(("+ " if k > 0 else "- ") + (nm if abs(k) == 1 else f"{abs(k)} * {nm}"))
    s = " ".join(out)
    return s[2:] if s.startswith("+ ") else ("-" + s[2:] if s else "0.0")

def wrap_sum(expr, indent, width=110):
    """Break a long ' + ' / ' - ' expression into continuation lines inside parentheses."""
    if len(expr) + indent <= width:
        return expr
    toks = expr.split(" ")
    lines, cur = [], ""
    for t in toks:
        if len(cur) + len(t) + 1 + indent > width and t in ("+", "-"):
            lines.append(cur)
            cur = t
        else:
            cur = (cur + " " + t).strip()
    lines.append(cur)
    return "(" + ("\n" + " " * (indent + 1)).join(lines) + ")"

g = [f"g{i}" for i in range(19)]
f = [f"f{i}" for i in range(19)]
n = [f"n{i}" for i in range(19)]

def moments_block(v):
    """Sum and first moments of the populations named ``v``, as source expressions."""
    rho = " + ".join(v)
    return rho, lin([c[0] for c in C], v), lin([c[1] for c in C], v), lin([c[2] for c in C], v)

