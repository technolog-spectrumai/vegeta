@triton.jit
def _axis_key(key, s, n, C: tl.constexpr, CODE_LO: tl.constexpr, CODE_HI: tl.constexpr, RANK: tl.constexpr):
    """Fold one axis into the boundary key ``code·4 + rank`` (rank 2, 1, 0 for x, y, z) of the winning face."""
    if C == 1:
        key = tl.where(s < 0, tl.maximum(key, CODE_LO * 4 + RANK), key)
    elif C == -1:
        key = tl.where(s >= n, tl.maximum(key, CODE_HI * 4 + RANK), key)
    return key


@triton.jit
def _wrap(s, n):
    return tl.where(s < 0, s + n, tl.where(s >= n, s - n, s))


@triton.jit
def _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om, yc, zc,
          I: tl.constexpr, CX: tl.constexpr, CY: tl.constexpr, CZ: tl.constexpr, W: tl.constexpr,
          OPP: tl.constexpr, K0: tl.constexpr, K1: tl.constexpr, K2: tl.constexpr, K3: tl.constexpr,
          K4: tl.constexpr, K5: tl.constexpr, HAS_SOLID: tl.constexpr, HAS_FACES: tl.constexpr,
          HAS_FRAME: tl.constexpr):
    """The population arriving at ``node`` along ``c_I``: pulled from ``node − c_I`` or supplied by a boundary."""
    if I == 0:
        return tl.load(f_ptr + node, mask=valid, other=0.0)
    sx = x - CX
    sy = y - CY
    sz = z - CZ
    src = (_wrap(sx, nx) * ny + _wrap(sy, ny)) * nz + _wrap(sz, nz)
    if HAS_FACES:
        key = tl.full(x.shape, -1, tl.int32)
        key = _axis_key(key, sx, nx, CX, K0, K1, 2)
        key = _axis_key(key, sy, ny, CY, K2, K3, 1)
        key = _axis_key(key, sz, nz, CZ, K4, K5, 0)
        kind = tl.where(key >= 0, key // 4, 0)
        on_face = kind > 0
    else:
        on_face = tl.zeros(x.shape, tl.int1)
    if HAS_SOLID:
        solid_link = ((links >> I) & 1) != 0
        bounce = on_face | solid_link
    else:
        bounce = on_face
    pulled = tl.load(f_ptr + I * N + src, mask=valid & (~bounce), other=0.0)
    back = tl.load(f_ptr + OPP * N + node, mask=valid & bounce, other=0.0)
    res = tl.where(bounce, back, pulled)                       # solid links and plain walls
    if HAS_FACES:
        rank = key % 4                                          # 2: x, 1: y, 0: z
        face = tl.where(rank == 2, 0 if CX == 1 else 1, tl.where(rank == 1, 2 if CY == 1 else 3, 4 if CZ == 1 else 5))
        face = tl.where(on_face, face, 0)
        uwx = tl.load(faces_ptr + face * 4 + 0, mask=on_face, other=0.0)
        uwy = tl.load(faces_ptr + face * 4 + 1, mask=on_face, other=0.0)
        uwz = tl.load(faces_ptr + face * 4 + 2, mask=on_face, other=0.0)
        rho_out = tl.load(faces_ptr + face * 4 + 3, mask=on_face, other=1.0)
        cuw = CX * uwx + CY * uwy + CZ * uwz
        if HAS_FRAME:
            # lab-frame wall/inlet velocity minus Ω×r at the halfway point x − c/2: c·(u − Ω×r)
            rym = y.to(tl.float32) - 0.5 * CY - yc
            rzm = z.to(tl.float32) - 0.5 * CZ - zc
            cuw += CY * om * rzm - CZ * om * rym
            moving = kind >= 2                                  # walls move in the rotating frame too
        else:
            moving = (kind == 2) | (kind == 3)
        res = tl.where(moving, back + (6.0 * W) * rho_ref * cuw, res)
        cub = CX * ubx + CY * uby + CZ * ubz
        res = tl.where(kind == 1, -back + (2.0 * W) * rho_out * (1.0 + 4.5 * cub * cub - 1.5 * usq_b), res)
    return res


@triton.jit
def _feq(rho, ux, uy, uz, usq, CX: tl.constexpr, CY: tl.constexpr, CZ: tl.constexpr, W: tl.constexpr):
    cu = CX * ux + CY * uy + CZ * uz
    return W * rho * (1.0 + 3.0 * cu + 4.5 * cu * cu - 1.5 * usq)


@triton.jit
def _relax_store(out_ptr, node, N, valid, fi, rho, ux, uy, uz, usq, fx, fy, fz, uf, omega, guo, solid_node, rho_ref,
                 jx1, jy1, jz1, pxx, pyy, pzz, pxy, pxz, pyz,
                 I: tl.constexpr, CX: tl.constexpr, CY: tl.constexpr, CZ: tl.constexpr, W: tl.constexpr,
                 HAS_FORCE: tl.constexpr, HAS_SOLID: tl.constexpr, REGULARIZED: tl.constexpr):
    """Relaxation of one population (BGK, or regularized BGK), Guo's source, and its store; solid nodes get
    the rest state."""
    cu = CX * ux + CY * uy + CZ * uz
    feq = W * rho * (1.0 + 3.0 * cu + 4.5 * cu * cu - 1.5 * usq)
    if REGULARIZED:
        qpi = ((CX * CX - 1.0 / 3.0) * pxx + (CY * CY - 1.0 / 3.0) * pyy + (CZ * CZ - 1.0 / 3.0) * pzz
               + 2.0 * (CX * CY * pxy + CX * CZ * pxz + CY * CZ * pyz))
        post = feq + (1.0 - omega) * W * (3.0 * (CX * jx1 + CY * jy1 + CZ * jz1) + 4.5 * qpi)
    else:
        post = fi - omega * (fi - feq)
    if HAS_FORCE:
        cf = CX * fx + CY * fy + CZ * fz
        post += guo * W * (3.0 * (cf - uf) + 9.0 * cu * cf)
    if HAS_SOLID:
        post = tl.where(solid_node, W * rho_ref, post)
    tl.store(out_ptr + I * N + node, post, mask=valid)


@triton.jit
def _local(f_ptr, node, N, m, I: tl.constexpr):
    return tl.load(f_ptr + I * N + node, mask=m, other=0.0)


@triton.jit
def _sponge(nu_x, d, sp_w, sp_nu, ON: tl.constexpr):
    """Sponge viscosity ``sp_nu ((w − d)/w)²`` within ``w`` of a face (``d`` from its halfway plane); max-combined."""
    if ON:
        a = (sp_w - d) / sp_w
        nu_x = tl.maximum(nu_x, tl.where(d < sp_w, sp_nu * a * a, 0.0))
    return nu_x


@triton.jit
def _neighbour(m_ptr, node, nb, N, valid, use_own, ux, uy, uz):
    """Previous-step velocity at node ``nb``, or the node's own where ``use_own`` (solid / beyond a wall face)."""
    m = valid & (~use_own)
    vx = tl.where(use_own, ux, tl.load(m_ptr + nb, mask=m, other=0.0))
    vy = tl.where(use_own, uy, tl.load(m_ptr + N + nb, mask=m, other=0.0))
    vz = tl.where(use_own, uz, tl.load(m_ptr + 2 * N + nb, mask=m, other=0.0))
    return vx, vy, vz


@triton.jit
def _wale(mprev_ptr, node, x, y, z, nx, ny, nz, N, valid, links, cw2, om,
          PX: tl.constexpr, PY: tl.constexpr, PZ: tl.constexpr, HAS_SOLID: tl.constexpr, HAS_FRAME: tl.constexpr):
    """WALE eddy viscosity from central differences of the previous step's velocity, in the lab frame (see
    mancha.turbulence)."""
    ux = tl.load(mprev_ptr + node, mask=valid, other=0.0)
    uy = tl.load(mprev_ptr + N + node, mask=valid, other=0.0)
    uz = tl.load(mprev_ptr + 2 * N + node, mask=valid, other=0.0)
    # x ± 1
    xp = x + 1
    xm = x - 1
    own_p = xp >= nx
    own_m = xm < 0
    if PX:
        xp = tl.where(own_p, 0, xp)
        xm = tl.where(own_m, nx - 1, xm)
        own_p = tl.zeros(x.shape, tl.int1)
        own_m = tl.zeros(x.shape, tl.int1)
    if HAS_SOLID:
        own_p = own_p | (((links >> 2) & 1) != 0)               # source of c = (−1,0,0) is x + 1
        own_m = own_m | (((links >> 1) & 1) != 0)
    apx, apy, apz = _neighbour(mprev_ptr, node, (xp * ny + y) * nz + z, N, valid, own_p, ux, uy, uz)
    amx, amy, amz = _neighbour(mprev_ptr, node, (xm * ny + y) * nz + z, N, valid, own_m, ux, uy, uz)
    # y ± 1
    yp = y + 1
    ym = y - 1
    own_p = yp >= ny
    own_m = ym < 0
    if PY:
        yp = tl.where(own_p, 0, yp)
        ym = tl.where(own_m, ny - 1, ym)
        own_p = tl.zeros(x.shape, tl.int1)
        own_m = tl.zeros(x.shape, tl.int1)
    if HAS_SOLID:
        own_p = own_p | (((links >> 4) & 1) != 0)
        own_m = own_m | (((links >> 3) & 1) != 0)
    bpx, bpy, bpz = _neighbour(mprev_ptr, node, (x * ny + yp) * nz + z, N, valid, own_p, ux, uy, uz)
    bmx, bmy, bmz = _neighbour(mprev_ptr, node, (x * ny + ym) * nz + z, N, valid, own_m, ux, uy, uz)
    # z ± 1
    zp = z + 1
    zm = z - 1
    own_p = zp >= nz
    own_m = zm < 0
    if PZ:
        zp = tl.where(own_p, 0, zp)
        zm = tl.where(own_m, nz - 1, zm)
        own_p = tl.zeros(x.shape, tl.int1)
        own_m = tl.zeros(x.shape, tl.int1)
    if HAS_SOLID:
        own_p = own_p | (((links >> 6) & 1) != 0)
        own_m = own_m | (((links >> 5) & 1) != 0)
    cpx, cpy, cpz = _neighbour(mprev_ptr, node, (x * ny + y) * nz + zp, N, valid, own_p, ux, uy, uz)
    cmx, cmy, cmz = _neighbour(mprev_ptr, node, (x * ny + y) * nz + zm, N, valid, own_m, ux, uy, uz)
    # g[i][j] = ∂u_i/∂x_j
    gxx = 0.5 * (apx - amx)
    gyx = 0.5 * (apy - amy)
    gzx = 0.5 * (apz - amz)
    gxy = 0.5 * (bpx - bmx)
    gyy = 0.5 * (bpy - bmy)
    gzy = 0.5 * (bpz - bmz)
    gxz = 0.5 * (cpx - cmx)
    gyz = 0.5 * (cpy - cmy)
    gzz = 0.5 * (cpz - cmz)
    if HAS_FRAME:                                               # lab-frame gradient: + ∇(Ω×r)
        gyz -= om
        gzy += om
    sxy = 0.5 * (gxy + gyx)
    sxz = 0.5 * (gxz + gzx)
    syz = 0.5 * (gyz + gzy)
    ss = gxx * gxx + gyy * gyy + gzz * gzz + 2.0 * (sxy * sxy + sxz * sxz + syz * syz)
    # (g²)_ij = Σ_k g_ik g_kj
    hxx = gxx * gxx + gxy * gyx + gxz * gzx
    hyy = gyx * gxy + gyy * gyy + gyz * gzy
    hzz = gzx * gxz + gzy * gyz + gzz * gzz
    hxy = gxx * gxy + gxy * gyy + gxz * gzy
    hyx = gyx * gxx + gyy * gyx + gyz * gzx
    hxz = gxx * gxz + gxy * gyz + gxz * gzz
    hzx = gzx * gxx + gzy * gyx + gzz * gzx
    hyz = gyx * gxz + gyy * gyz + gyz * gzz
    hzy = gzx * gxy + gzy * gyy + gzz * gzy
    tr = (hxx + hyy + hzz) / 3.0
    dxx = hxx - tr
    dyy = hyy - tr
    dzz = hzz - tr
    dxy = 0.5 * (hxy + hyx)
    dxz = 0.5 * (hxz + hzx)
    dyz = 0.5 * (hyz + hzy)
    sdsd = dxx * dxx + dyy * dyy + dzz * dzz + 2.0 * (dxy * dxy + dxz * dxz + dyz * dyz)
    rs = tl.sqrt(sdsd)
    num = sdsd * rs                                             # (S^d:S^d)^(3/2)
    den = ss * ss * tl.sqrt(ss) + sdsd * tl.sqrt(rs)            # (S:S)^(5/2) + (S^d:S^d)^(5/4)
    return cw2 * num / (den + 1e-30)


@triton.jit
def stream_collide(f_ptr, out_ptr, links_ptr, faces_ptr, mprev_ptr, mnew_ptr, nx, ny, nz, N, omega, nu0, cw2,
                   rho_ref, fx, fy, fz, om, yc, zc, sp_w, sp_nu,
                   K0: tl.constexpr, K1: tl.constexpr, K2: tl.constexpr, K3: tl.constexpr, K4: tl.constexpr,
                   K5: tl.constexpr, SP0: tl.constexpr, SP1: tl.constexpr, SP2: tl.constexpr, SP3: tl.constexpr,
                   SP4: tl.constexpr, SP5: tl.constexpr, HAS_SPONGE: tl.constexpr, HAS_SOLID: tl.constexpr,
                   HAS_FACES: tl.constexpr, HAS_PRESSURE: tl.constexpr, HAS_FORCE: tl.constexpr,
                   HAS_FRAME: tl.constexpr, HAS_LES: tl.constexpr, REGULARIZED: tl.constexpr, INT64: tl.constexpr,
                   BLOCK: tl.constexpr):
    """One time step for ``BLOCK`` nodes: pull (with boundaries), moments, collision (BGK or regularized, with
    Guo forcing for a uniform force and the rotating frame's forces, WALE eddy viscosity), store."""
    pid = tl.program_id(0)
    if INT64:
        node = pid.to(tl.int64) * BLOCK + tl.arange(0, BLOCK).to(tl.int64)
    else:
        node = pid * BLOCK + tl.arange(0, BLOCK)
    valid = node < N
    z = node % nz
    y = (node // nz) % ny
    x = node // (ny * nz)
    if HAS_SOLID:
        links = tl.load(links_ptr + node, mask=valid, other=0)
        solid_node = ((links >> SOLID_BIT) & 1) != 0
    else:
        links = tl.zeros(node.shape, tl.int32)
        solid_node = tl.zeros(node.shape, tl.int1)
    ryn = y.to(tl.float32) - yc                                 # radial position (rotating frame)
    rzn = z.to(tl.float32) - zc
    d = 1.0 + om * om

    # velocity of the stored (post-collision) state at the node itself, needed by pressure faces only
    ubx = tl.zeros(node.shape, tl.float32)
    uby = tl.zeros(node.shape, tl.float32)
    ubz = tl.zeros(node.shape, tl.float32)
    usq_b = tl.zeros(node.shape, tl.float32)
    if HAS_PRESSURE:
        mp = tl.zeros(node.shape, tl.int1)
        if K0 == PRESSURE:
            mp = mp | (x == 0)
        if K1 == PRESSURE:
            mp = mp | (x == nx - 1)
        if K2 == PRESSURE:
            mp = mp | (y == 0)
        if K3 == PRESSURE:
            mp = mp | (y == ny - 1)
        if K4 == PRESSURE:
            mp = mp | (z == 0)
        if K5 == PRESSURE:
            mp = mp | (z == nz - 1)
        mp = mp & valid
        g0 = _local(f_ptr, node, N, mp, 0)
        g1 = _local(f_ptr, node, N, mp, 1)
        g2 = _local(f_ptr, node, N, mp, 2)
        g3 = _local(f_ptr, node, N, mp, 3)
        g4 = _local(f_ptr, node, N, mp, 4)
        g5 = _local(f_ptr, node, N, mp, 5)
        g6 = _local(f_ptr, node, N, mp, 6)
        g7 = _local(f_ptr, node, N, mp, 7)
        g8 = _local(f_ptr, node, N, mp, 8)
        g9 = _local(f_ptr, node, N, mp, 9)
        g10 = _local(f_ptr, node, N, mp, 10)
        g11 = _local(f_ptr, node, N, mp, 11)
        g12 = _local(f_ptr, node, N, mp, 12)
        g13 = _local(f_ptr, node, N, mp, 13)
        g14 = _local(f_ptr, node, N, mp, 14)
        g15 = _local(f_ptr, node, N, mp, 15)
        g16 = _local(f_ptr, node, N, mp, 16)
        g17 = _local(f_ptr, node, N, mp, 17)
        g18 = _local(f_ptr, node, N, mp, 18)
        rb = (g0 + g1 + g2 + g3 + g4 + g5 + g6 + g7 + g8 + g9 + g10 + g11 + g12 + g13 + g14 + g15 + g16 + g17 + g18)
        rb = tl.where(mp, rb, 1.0)
        bx = (g1 - g2 + g7 - g8 + g9 - g10 + g11 - g12 + g13 - g14 - 0.5 * fx) / rb
        by = (g3 - g4 + g7 - g8 - g9 + g10 + g15 - g16 + g17 - g18 - 0.5 * fy) / rb
        bz = (g5 - g6 + g11 - g12 - g13 + g14 + g15 - g16 - g17 + g18 - 0.5 * fz) / rb
        if HAS_FRAME:
            by -= 0.5 * om * om * ryn
            bz -= 0.5 * om * om * rzn
            ubx = bx
            uby = (by - om * bz) / d
            ubz = (bz + om * by) / d
        else:
            ubx = bx
            uby = by
            ubz = bz
        usq_b = ubx * ubx + uby * uby + ubz * ubz

    f0 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 0, 0, 0, 0, W0, 0, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f1 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 1, 1, 0, 0, W1, 2, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f2 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 2, -1, 0, 0, W1, 1, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f3 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 3, 0, 1, 0, W1, 4, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f4 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 4, 0, -1, 0, W1, 3, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f5 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 5, 0, 0, 1, W1, 6, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f6 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 6, 0, 0, -1, W1, 5, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f7 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 7, 1, 1, 0, W2, 8, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f8 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 8, -1, -1, 0, W2, 7, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f9 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 9, 1, -1, 0, W2, 10, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f10 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 10, -1, 1, 0, W2, 9, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
    f11 = _pull(f_ptr, faces_ptr, node, x, y, z, nx, ny, nz, N, valid, links, rho_ref, ubx, uby, ubz, usq_b, om,
               yc, zc, 11, 1, 0, 1, W2, 12, K0, K1, K2, K3, K4, K5, HAS_SOLID, HAS_FACES, HAS_FRAME)
