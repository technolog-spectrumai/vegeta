"""Triton kernels for D3Q19: fused pull-stream + boundaries + collision, and the macroscopic fields.

GENERATED by benchmarks/tools/gen_triton_kernels.py — edit the generator, not this file. The per-direction code is
unrolled because Triton has no arrays of tensors.

Memory layout (structure of arrays): population ``i`` of node ``n = (x·ny + y)·nz + z`` lives at
``f[i·N + n]``. A program handles ``BLOCK`` consecutive nodes, which share ``x`` and ``y`` except at row ends, so
for every direction the loads ``f[i·N + n − offset(c_i)]`` and the stores ``f_out[i·N + n]`` are contiguous runs
of ``BLOCK`` floats: coalesced (the loads are shifted by the neighbour offset, so they are not aligned to
128-byte lines; each warp touches at most one extra line per direction). Per node and step: 19 loads + 19 stores
of 4 bytes, plus a 4-byte link mask when solids are present, plus 3 stores and 21 (mostly cached) loads of the
velocity field with LES.

Everything follows the NumPy reference exactly (same boundary precedence and formulas, same rotating-frame and
WALE discretisations, same regularization); the tests compare the two. Optional physics are compile-time
switches: an all-periodic BGK run compiles to the plain kernel.

The numbering below must match :class:`mancha.lattice.D3Q19` (checked by the tests).
"""
