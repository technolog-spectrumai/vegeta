    bx = (f1 - f2 + f7 - f8 + f9 - f10 + f11 - f12 + f13 - f14 + 0.5 * fx) * inv
    by = (f3 - f4 + f7 - f8 - f9 + f10 + f15 - f16 + f17 - f18 + 0.5 * fy) * inv
    bz = (f5 - f6 + f11 - f12 - f13 + f14 + f15 - f16 - f17 + f18 + 0.5 * fz) * inv
