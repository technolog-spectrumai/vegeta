"""``python -m auseklis.report [out.md]``: regenerate the numbers of the technical specification from the models.
Every table below is computed, never typed. Cheap (seconds); runs no external solver."""
from __future__ import annotations

import sys

import numpy as np

from . import capture as C, mission as M, physics as ph, rendezvous as R, trade as T, variants as V
from .provenance import ASSUMED, register_table


def md_table(header, rows):
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(map(str, r)) + " |" for r in rows])


def build() -> str:
    out = ["# Auseklis: computed results (generated by `python -m auseklis.report`; all CALCULATED from ASSUMED inputs)\n"]
    r0 = ph.radius(V.ALT_KM)
    out += [f"## Reference orbit\n", f"- Sun-synchronous inclination at {V.ALT_KM:g} km: **{ph.sso_inclination_deg(V.ALT_KM):.2f} deg** (requirement 97.6 deg)",
            f"- Circular speed {ph.v_circ(r0):.0f} m/s, period {ph.period(r0) / 60:.1f} min, eclipse (beta=0) {ph.eclipse_fraction(V.ALT_KM, 0) * ph.period(r0) / 60:.1f} min",
            f"- Drag Δv to hold 550 km: {ph.drag_dv_per_year(550, 0.0125, 'min'):.2f} / {ph.drag_dv_per_year(550, 0.0125, 'mod'):.2f} / {ph.drag_dv_per_year(550, 0.0125, 'max'):.2f} m/s per year (solar min / moderate / max, Cd A/m = 0.0125 m²/kg, ASSUMED density table, expect a factor ~2-3 uncertainty)",
            f"- Hohmann 550→570 km: {ph.hohmann(r0, ph.radius(570))['dv']:.1f} m/s; plane change of 1 deg: {ph.plane_change_dv(ph.v_circ(r0), np.radians(1)):.0f} m/s (so a 500 m/s budget cannot buy more than ~3.9 deg of plane change)\n"]
    out += ["- RAAN gap closure by altitude drift: ±20 km gives "
            f"{abs(ph.differential_raan_rate_deg_per_day(550, 97.6, 20)):.3f} deg/day, so 1 deg takes {1 / abs(ph.differential_raan_rate_deg_per_day(550, 97.6, 20)):.0f} days; "
            f"±50 km gives {abs(ph.differential_raan_rate_deg_per_day(550, 97.6, 50)):.3f} deg/day. **Targets must already be in (nearly) the servicer's plane.**\n"]
    rows = []
    for mass, d in M.DEBRIS.items():
        alts = [M.disposal_altitude_km(d, activity=a) for a in ("min", "mod", "max")]
        rows.append([f"{mass} kg", *[f"{x:.0f}" for x in alts]])
    out += ["## 5-year hand-over altitude vs solar activity (circular-equivalent, ASSUMED density table)\n", md_table(["debris", "solar min km", "moderate km", "solar max km"], rows), ""]
    rows = []
    for k in "AC":
        for act in ("min", "mod", "max"):
            c = M.campaign(V.VARIANTS[k], M.DEBRIS[250], activity=act)
            f = c["first"]
            rows.append([k, act, f"{f['handover_alt_km']:.0f}", f"{f['dv_total']:.0f}", f"{f['propellant']:.1f}", c["removals"], c["limiting"]])
    out += ["## Sensitivity: 250 kg removals vs the solar-activity assumption\n", md_table(["var", "activity", "hand-over km", "Δv m/s", "prop kg", "removals / life", "limited by"], rows), ""]
    ar = V.array_sizing()
    out += [f"## Power\n", f"- Array for 1.5 kW EOL after 5 years: **{ar['area']:.2f} m²** ({ar['array_mass']:.1f} kg); battery for a {ar['eclipse_min']:.1f} min eclipse at 380 W, DoD 30 %: **{ar['battery_wh']:.0f} Wh** ({ar['battery_kg']:.1f} kg)\n"]
    rows = []
    for k, v in V.VARIANTS.items():
        for mode, kw in (("sized for 500 m/s", {}), ("filled to 400 kg", {"wet_target": 400.0})):
            b = V.budget(v, **kw)
            rows.append([k, mode, f"{b['dry_nominal']:.0f}", f"{b['dry_with_margin']:.0f}", f"{b['propellant']:.0f}", f"{b['rcs_propellant']:.0f}", f"{b['wet']:.0f}", f"{b['dv_capability']:.0f}", "yes" if b["within_mass_window"] else "NO (<350 kg)"])
    out += ["## Mass and Δv budgets\n", md_table(["var", "mode", "dry nominal kg", "dry +25 % kg", "main prop kg", "RCS prop kg", "wet kg", "Δv m/s", "in 350-500 kg"], rows), ""]
    rows = []
    for k, v in V.VARIANTS.items():
        for mode, x in V.power_modes(v).items():
            rows.append([k, mode, x["load_w"], x["margin_w"], "ok" if x["ok"] else "OVER"])
    out += ["## Power modes (1500 W EOL, 90 % usable)\n", md_table(["var", "mode", "load W", "margin W", ""], rows), ""]
    rows = []
    for k, v in V.VARIANTS.items():
        for mass, d in M.DEBRIS.items():
            for mode in ("decay5", "reentry"):
                c = M.campaign(v, d, mode)
                f = c.get("first", {})
                rows.append([k, f"{mass} kg", mode, "-" if not f.get("feasible") else f"{f['handover_alt_km']:.0f}", "-" if not f.get("feasible") else f"{f['dv_total']:.0f}",
                             "-" if not f.get("feasible") else f"{f['propellant']:.1f}", "-" if not f.get("feasible") else f"{f['days']:.0f}", c["removals"], c["limiting"]])
    out += ["## Per-removal ledger and 5-year throughput (400 kg wet, 10 % reserve)\n", md_table(["var", "debris", "disposal", "hand-over km", "Δv m/s", "prop kg", "days", "removals / life", "limited by"], rows), ""]
    rows = [[f"{g['range_m']:.0f}", f"{g['sigma_pos_m']:.2f}", g["v_max_m_s"], f"{g['time_to_go_min_at_vmax']:.0f}", g["keep_out_m"], g["horizon_min"], f"{g['passive_p01_min_sep_m']:.0f}", "yes" if g["passively_safe"] else "NO"] for g in R.gate_table()]
    out += ["## Approach gates (passive safety: thrusters off, Monte-Carlo CW drift)\n", md_table(["range m", "σ_pos m (ASSUMED)", "v_max m/s", "min to go at v_max", "keep-out m", "horizon min", "1st-percentile min sep m", "passively safe"], rows), ""]
    Is, Id = C.box_inertia(400, 1, 1, 1.2), C.cylinder_inertia(500, .8, 3.6)
    w, H, m, I, com = C.capture_rate(400, Is, 500, Id, np.radians([0, 3, 0]), [2.5, 0, 0])
    cf = C.contact_1d(400, 500, 0.05, 2000.0, 300.0)
    out += ["## Capture (500 kg, 3 deg/s tumble, 0.05 m/s closing, arm 2 kN/m, 300 N s/m)\n",
            f"- Angular momentum {np.linalg.norm(H):.1f} N m s → combined rate {np.degrees(np.linalg.norm(w)):.2f} deg/s; RCS detumble propellant {C.detumble_propellant(np.linalg.norm(H), 0.8, 220) * 1e3:.0f} g",
            f"- Contact: impulse {C.impulsive_capture(400, 500, 0.05)['impulse_Ns']:.1f} N s; peak arm force {cf['peak_force_N']:.0f} N (undamped analytic {cf['analytic_undamped_N']:.0f} N)\n"]
    t = T.matrix()
    out += ["## Trade matrix (weights ASSUMED)\n", md_table(["variant", "weighted score"] , [[k, f"{x:.2f}"] for k, x in t["total"].items()]),
            f"\nWinner: **{t['winner']}**; share of weight perturbations won: " + ", ".join(f"{k} {x:.0%}" for k, x in T.weight_sensitivity().items()) + "\n"]
    reg = register_table(ASSUMED)
    out += [f"## Assumption register: {len(reg)} ASSUMED values\n", md_table(["name", "value", "unit", "note"], [[n, f"{v:g}", u, note] for n, v, u, tag, note in reg])]
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    if len(sys.argv) > 1:
        open(sys.argv[1], "w").write(text)
    print(text)
