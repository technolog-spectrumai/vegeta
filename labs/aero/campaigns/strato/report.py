"""Strato — the feasibility report, written from the campaign's JSON results (``run.py``). Every number in it is read
from a result file; the sentences that state findings are computed from those numbers, not typed in."""
from __future__ import annotations

import json
import math
from pathlib import Path


def _load(out: Path, name: str):
    p = out / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def f(v, nd=1, unit=""):
    if v is None or (isinstance(v, float) and not math.isfinite(v)):
        return "—"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, (int, float)):
        s = f"{v:,.{nd}f}"
        return f"{s} {unit}".strip()
    return str(v)


def table(rows, cols) -> str:
    head = "| " + " | ".join(c[0] for c in cols) + " |\n|" + "|".join("---:" if c[2] else "---" for c in cols) + "|\n"
    body = "".join("| " + " | ".join(c[1](r) for c in cols) + " |\n" for r in rows)
    return head + body


VERIFIED = [
    ("Standard atmosphere 0–86 km, gravity vs altitude", "og.stratosphere", "verified: USSA-1976 tables (tests)"),
    ("Buoyancy, gas laws, sealed vs vented cells", "og.lifting_gas", "verified: ideal gas, Archimedes (tests)"),
    ("Sun position, day length, horizon dip", "og.solar", "verified: NOAA algorithm (tests)"),
    ("Membrane forces, bending, wrinkling", "og.envelope", "verified: membrane theory (tests)"),
    ("Hull volume, area, centre of buoyancy", "strato_geometry", "verified: analytic profile = CAD solid within 0.01 %"),
    ("Added mass, Munk moment", "strato_aero.lamb_k", "verified: Lamb's coefficients (tests)"),
    ("Clear-sky beam above the clouds", "og.solar.beam_normal", "estimate: Meinel relation, pressure-scaled air mass"),
    ("Hull and appendage drag", "strato_aero.drag", "estimate: Hoerner build-up; C_DV plausibility band only"),
    ("Fin effectiveness, stability margin", "strato_aero.stability", "estimate: low-AR lift slope, wake factor"),
    ("Propeller efficiency", "strato_aero.propeller_efficiency", "physics (actuator disc) × estimated profile factor"),
    ("Gas superheat, cell temperature", "strato_thermal", "estimate: two-node lumped model, assumed coefficients"),
    ("Stratospheric winds over Europe", "strato_wind", "estimate: parametric climatology, not ERA5 data"),
    ("Component masses, efficiencies, strengths", "strato_catalogue", "estimate: technology-class values, not datasheets"),
    ("Sea wind, cheap-part masses and prices (Zeppelin-Micro)", "zeppelin_micro", "estimate: Weibull sea wind, retail order of magnitude"),
    ("CFD of the hull, FEM of the fins", "Aeromant / Talos", "NOT RUN (OpenFOAM and CalculiX not installed here)"),
]


def write(out: Path) -> Path:
    atm, wind, fam, pv, det = (_load(out, n) for n in ("atmosphere", "wind", "family", "pv", "detail"))
    sw_, sens, par, sea, con = (_load(out, n) for n in ("sweeps", "sensitivity", "pareto", "seasons", "constraints"))
    cad = _load(out, "cad")
    img = _load(out, "sigma")
    micro = _load(out, "zeppelin_micro")
    L = []
    w = L.append
    quick = any(r and r.get("quick") for r in (atm, wind, fam, pv, det, sw_, sens, par, sea, con, cad))
    w("# Strato — feasibility of a solar-electric stratospheric airship (HAPS)\n")
    w("Generated by `labs/aero/campaigns/strato/run.py` from the result files in this folder. Stage V8 of `todo.md`; "
      "assumptions and sources in `labs/aero/designs/STRATO.md`.\n")
    if quick:
        w("> **QUICK RUN** — the searches were shrunk for a test; these numbers are not the study's.\n")

    # ------------------------------------------------------------------------------------------- findings
    w("## Findings\n")
    if fam:
        rows = fam["table"]
        meets = {s: sorted(float(r["length"]) for r in rows if r["scenario"] == s and r["meets"]) for s in ("summer", "year")}
        for s, label in (("summer", "summer (Jun–Aug, ≥ 90 % of days on station, ≥ 60 days of gas)"),
                         ("year", "year-round (Mar/Jun/Sep/Dec, ≥ 50 % of days in the worst month, ≥ 60 days of gas)")):
            if meets[s]:
                best = max((r for r in rows if r["scenario"] == s and r["meets"]), key=lambda r: r["payload"])
                w(f"- **{label}**: the smallest optimised ship that meets it is **{meets[s][0]:g} m**; the best payload "
                  f"found is **{f(best['payload'])} kg** on the {f(best['length'], 0)} m ship "
                  f"(fineness {f(best['fineness'], 2)}, {f(best['altitude'] / 1000, 1)} km).")
            else:
                w(f"- **{label}**: no ship up to {max(float(r['length']) for r in rows):g} m met it within the bounds.")
        demo = fam.get("demonstrator", {})
        b = demo.get("best", {})
        if demo.get("meets"):
            w(f"- **The 15 m × 3.5 m-class demonstrator cannot reach 18–22 km**: at most "
              f"**{f(b['design']['altitude'] / 1000, 1)} km** with {f(b['payload'])} kg of payload in July (best of the "
              f"altitude search; fineness {f(b['design']['fineness'], 2)}).")
        elif b:
            w(f"- **The 15 m demonstrator found no feasible float altitude** in 6–22 km for July "
              f"(least-bad design: {'; '.join(b.get('problems', [])) or 'missed the requirements'}).")
        s15 = [r for r in rows if r["scenario"] == "summer" and float(r["length"]) == 15.0]
        if s15:
            w(f"  At 20 km a 15 m hull of fineness {f(s15[0]['fineness'], 2)} lifts {f(s15[0]['net_lift'])} kg in all; "
              f"its envelope alone weighs {f(_mass(fam, '15.0', 'envelope'))} kg.")
    if sens and sens.get("rows"):
        if sens.get("noise") is not None:
            w(f"- **Optimiser noise**: the base case repeated with three seeds gives {', '.join(f(v) for v in sens['base_seeds'])} kg "
              f"(spread {f(sens['noise'])} kg); sensitivities smaller than that are not resolved.")
        top = max(sens["rows"], key=lambda r: abs((r["payload_high"] or 0) - (r["payload_low"] or 0)))
        w(f"- **The limiting estimate** for the {f(80, 0)} m reference ship is **{top['estimate']}**: "
          f"×{top['low_factor']:g} → {f(top['payload_low'])} kg, ×{top['high_factor']:g} → {f(top['payload_high'])} kg "
          f"(base {f(sens['base_payload'])} kg of maximum payload).")
    if pv:
        g, c = pv.get("gaas/summer", {}), pv.get("cigs/summer", {})
        if g and c:
            w(f"- **GaAs vs CIGS** (80 m, summer): {f(g['best'].get('payload'))} kg vs {f(c['best'].get('payload'))} kg payload "
              f"(meets: {f(g['meets'])} / {f(c['meets'])}); year-round {f(pv['gaas/year']['best'].get('payload'))} kg vs "
              f"{f(pv['cigs/year']['best'].get('payload'))} kg (meets: {f(pv['gaas/year']['meets'])} / {f(pv['cigs/year']['meets'])}).")
    if det:
        es, ev = det.get("endurance/sealed/Jul"), det.get("endurance/vented/Jul")
        if es and ev:
            lost = ev["lost_at_s"]
            w(f"- **Sealed vs vented** (reference ship, July): sealed holds {f(es['min_altitude'] / 1000, 2)} km or more for "
              f"{f(es['days_simulated'], 0)} days ({f(es['on_station'] * 100, 0)} % of the time on station); vented "
              + (f"is lost after {f(lost / 86400, 1)} days (venting by day, sinking by night; {f(ev['vented_kg'])} kg of helium vented)."
                 if lost is not None else f"stays up for {f(ev['days_simulated'], 0)} days with {f(ev['ballast_left'])} kg of ballast left."))
    if img:
        if img.get("design"):
            v = img["verdict"]
            w(f"- **Strato-Sigma, the smallest imaging Strato** ({img['payload_note']}) for the summer scenario is **{f(img['length'], 1)} m** "
              f"long ({f(v['diameter'], 1)} m diameter, {f(v['volume'], 0)} m³, {f(v['system_mass'], 0)} kg at "
              f"{f(img['design']['altitude'] / 1000, 1)} km); the envelope is {f(v['masses'].get('envelope'), 0)} kg of it.")
        else:
            w(f"- **No Strato-Sigma (imaging) up to {max(float(k) for k in img['steps']):g} m** met the summer scenario.")
    if micro and micro.get("best"):
        b = micro["best"]
        w(f"- **Zeppelin-Micro**, a maritime imaging airship at {f(micro['mission']['altitude'], 0)} m: the cheapest is "
          f"**{b['concept']}**, {b['design']['envelope']}, **{f(b['length'], 1)} m × {f(b['diameter'], 1)} m** "
          f"({f(b['volume'], 0)} m³, {f(b['system_mass'], 1)} kg), about **€{f(b['first_year_cost'] / 1000, 1)}k** in its "
          f"first year (estimate) for a {f(micro['mission']['design_wind'], 0)} m/s design wind "
          f"(~{f(b['operable_fraction'] * 100, 0)} % of hours at sea).")
    w("")

    # ------------------------------------------------------------------------------------------- Zeppelin-Micro
    if micro and micro.get("best"):
        m_ = micro["mission"]
        w("## Zeppelin-Micro: the cheapest maritime imaging airship\n")
        w("It stays in the troposphere, so it is a Zeppelin; the Strato name is kept for ships that float in the stratosphere.\n")
        w(f"A daylight camera with a video link lifted to {f(m_['altitude'], 0)} m above the sea for {f(m_['hours'], 0)} h per "
          f"deployment, working in winds up to {f(m_['design_wind'], 0)} m/s at that height. Tethered aerostat (no propulsion; "
          "camera on a small battery, video by radio, an unpowered Dyneema line) against a free-flying micro blimp "
          "(electric propellers that out-fly the design wind by 3 m/s, a battery for the hours). Masses, prices and the "
          "sea-wind statistics are estimates (`designs/zeppelin_micro.py`); the costs compare options, they do not price a product.\n")
        w(table([r for r in micro["rows"] if r.get("feasible")], [
            ("concept", lambda r: r["concept"], False), ("envelope", lambda r: r["design"]["envelope"], False),
            ("fin scale", lambda r: f(r["design"]["fin_scale"], 1), True),
            ("L × D [m]", lambda r: f"{f(r['length'], 2)} × {f(r['diameter'], 2)}", True), ("V [m³]", lambda r: f(r["volume"], 1), True),
            ("mass [kg]", lambda r: f(r["system_mass"], 1), True), ("propulsion [W]", lambda r: f(r["propulsion_w"], 0), True),
            ("battery [Wh]", lambda r: f(r["battery_wh"], 0), True), ("build [€]", lambda r: f(r["build_cost"], 0), True),
            ("ground [€]", lambda r: f(r["ground_cost"], 0), True), ("helium/yr [€]", lambda r: f(r["helium_cost_per_year"], 0), True),
            ("first year [€]", lambda r: f(r["first_year_cost"], 0), True)]))
        w("")
        th = micro.get("thermal", {}).get("best")
        if th:
            b = micro["best"]
            w("With and without a thermal camera (each the cheapest sized option):\n")
            w(table([dict(cam="daylight", **b), dict(cam="daylight + thermal", **th)], [
                ("camera", lambda r: r["cam"], False), ("concept", lambda r: r["concept"], False),
                ("L × D [m]", lambda r: f"{f(r['length'], 2)} × {f(r['diameter'], 2)}", True), ("V [m³]", lambda r: f(r["volume"], 1), True),
                ("mass [kg]", lambda r: f(r["system_mass"], 1), True), ("payload power [W]", lambda r: f(r["loads_w"], 0), True),
                ("build [€]", lambda r: f(r["build_cost"], 0), True), ("helium/yr [€]", lambda r: f(r["helium_cost_per_year"], 0), True),
                ("first year [€]", lambda r: f(r["first_year_cost"], 0), True)]))
            w("")
        w(table(micro["altitude"], [("altitude [m]", lambda r: f(r["altitude"], 0), True), ("length [m]", lambda r: f(r["length"], 2), True),
                                    ("volume [m³]", lambda r: f(r["volume"], 1), True), ("mass [kg]", lambda r: f(r["system_mass"], 1), True),
                                    ("build [€]", lambda r: f(r["build_cost"], 0), True)]))
        w("")
        for p_ in micro["plots"]:
            w(f"![Zeppelin-Micro]({p_})\n")

    # ------------------------------------------------------------------------------------------- Strato-Sigma
    if img and img.get("design"):
        v, d = img["verdict"], img["design"]
        w("## Strato-Sigma: the smallest ship for imaging (summer)\n")
        w(f"Payload: {img['payload_note']}: {f(img['payload']['payload_mass'])} kg, {f(img['payload']['payload_power'], 0)} W by day, "
          f"{f(img['payload']['payload_power_night'], 0)} W at night. Found by bisection on the length with an optimisation of "
          "everything else at each step (`strato_study.smallest_length`); \"impossible\" below means the search found no design "
          "within the bounds, not a proof that none exists.\n")
        w(table([dict(L=k, **x) for k, x in sorted(img["steps"].items(), key=lambda kv: float(kv[0]))], [
            ("length [m]", lambda r: f(float(r["L"]), 2), True), ("meets", lambda r: f(r["meets"]), False),
            ("surplus lift [kg]", lambda r: f(r["surplus_lift"]), True), ("problems", lambda r: "; ".join(r["problems"] or []), False)]))
        w("")
        w(table([{"k": k, "v": x} for k, x in (
            ("length × diameter [m]", f"{f(d['length'], 1)} × {f(v['diameter'], 2)} (fineness {f(d['fineness'], 2)})"),
            ("volume [m³]", f(v["volume"], 0)), ("float altitude [km]", f(d["altitude"] / 1000, 2)),
            ("system mass / net lift [kg]", f"{f(v['system_mass'], 1)} / {f(v['net_lift'], 1)}"),
            ("battery [kWh]", f(d["battery_energy"] / 1000, 2)), ("propulsion [kW]", f(d["propulsion_power"] / 1000, 2)),
            ("array [m²]", f(v["solar_area"], 0)), ("envelope plies", f(v["plies"], 0)),
            ("superpressure night–noon [Pa]", f"{f(v['dp_min'], 0)} – {f(v['dp_max'], 0)}"),
            ("days on station (worst of Jun–Aug)", f(v["availability"] * 100, 0, "%")),
            ("gas life [days]", f(v["gas_life_days"], 0)))],
            [("", lambda r: r["k"], False), ("", lambda r: r["v"], True)]))
        w("")
        w(table([dict(month=k, **x) for k, x in img["months"].items()], [
            ("month", lambda r: r["month"], False), ("feasible", lambda r: f(r["feasible"]), False),
            ("days on station", lambda r: f(r["availability"] * 100, 0, "%"), True), ("surplus [kg]", lambda r: f(r["surplus_lift"]), True),
            ("noon superheat [K]", lambda r: f(r["superheat_day"]), True), ("problems", lambda r: "; ".join(r["problems"]), False)]))
        e, a = img["endurance"], img["ascent"]
        w(f"\n30 days in July: {f(e['on_station'] * 100, 0)} % of the time on station, lowest {f(e['min_altitude'] / 1000, 2)} km, "
          f"{f(e['gas_lost_kg'], 2)} kg of helium lost{'' if e['lost_at_s'] is None else ', lost after ' + f(e['lost_at_s'] / 86400, 1) + ' days'}. "
          f"Ascent: {f(a['time_to_99pct_s'] / 3600 if a['time_to_99pct_s'] else None, 1)} h to float, drift {f(a['drift_km'], 0)} km.\n")
        for p_ in img["plots"]:
            w(f"![Strato-Sigma]({p_})\n")

    # ------------------------------------------------------------------------------------------- family
    if fam:
        w("## The 15–120 m family (optimised)\n")
        w("Each ship is the differential-evolution optimum of its length: the highest payload that passes the "
          "feasibility gate and meets the scenario; where nothing meets it, the least-bad design found is shown "
          "(\"meets\" = no) with the reasons.\n")
        w(table(fam["table"], [
            ("scenario", lambda r: r["scenario"], False), ("L [m]", lambda r: f(r["length"], 0), True),
            ("D [m]", lambda r: f(r["diameter"]), True), ("V [m³]", lambda r: f(r["volume"], 0), True),
            ("alt [km]", lambda r: f(r["altitude"] / 1000, 1), True), ("payload [kg]", lambda r: f(r["payload"]), True),
            ("mass [kg]", lambda r: f(r["system_mass"], 0), True), ("net lift [kg]", lambda r: f(r["net_lift"], 0), True),
            ("battery [kWh]", lambda r: f(r["battery_wh"] / 1000), True), ("prop [kW]", lambda r: f(r["propulsion_w"] / 1000), True),
            ("array [m²]", lambda r: f(r["solar_area"], 0), True), ("avail.", lambda r: f(r["availability"] * 100, 0, "%"), True),
            ("gas life [d]", lambda r: f(r["gas_life_days"], 0), True), ("meets", lambda r: f(r["meets"]), False),
            ("problems", lambda r: r["problems"] or "", False)]))
        w("\n![family](family.png)\n")
    if cad and cad.get("plots"):
        w("Optimised ships (CAD, STEP files in `results/cad/`):\n")
        for p in cad["plots"]:
            w(f"![{p}]({p})\n")

    # ------------------------------------------------------------------------------------------- detail
    if det:
        w("## Reference ship: day and night, endurance, ascent\n")
        w(table([dict(month=k, **v) for k, v in det.items() if k in ("Jul", "Dec")], [
            ("month", lambda r: r["month"], False), ("array [kWh/day]", lambda r: f(r["solar_kwh"], 0), True),
            ("loads at p90 wind [kWh/day]", lambda r: f(r["loads_kwh"], 0), True), ("battery low [% usable]", lambda r: f(r["soc_min_pct"], 0), True),
            ("held all day", lambda r: f(r["held"]), False), ("noon superheat [K]", lambda r: f(r["superheat_max"]), True),
            ("superpressure [Pa]", lambda r: f"{f(r['dp_min'], 0)} – {f(r['dp_max'], 0)}", True)]))
        w("\n![day cycle](day_cycle.png)\n")
        w(table([dict(case=k.split("/", 1)[1], **v) for k, v in det.items() if k.startswith("endurance/")], [
            ("case", lambda r: r["case"], False), ("days", lambda r: f(r["days_simulated"], 1), True),
            ("on station", lambda r: f(r["on_station"] * 100, 0, "%"), True), ("lowest [km]", lambda r: f(r["min_altitude"] / 1000, 2), True),
            ("farthest [km]", lambda r: f(r["max_dist_km"], 1), True), ("He lost [kg]", lambda r: f(r["gas_lost_kg"]), True),
            ("vented [kg]", lambda r: f(r["vented_kg"]), True), ("ballast left [kg]", lambda r: f(r["ballast_left"]), True),
            ("lost after [d]", lambda r: f(r["lost_at_s"] / 86400 if r["lost_at_s"] is not None else None, 1), True)]))
        w("\n![endurance](endurance.png)\n")
        w(table([dict(case=k.split("/", 1)[1], **v) for k, v in det.items() if k.startswith("ascent/")], [
            ("gas system", lambda r: r["case"], False), ("float [km]", lambda r: f(r["float_altitude"] / 1000, 2), True),
            ("to 99 % [h]", lambda r: f(r["time_to_99pct_s"] / 3600 if r["time_to_99pct_s"] else None, 2), True),
            ("max rate [m/s]", lambda r: f(r["max_rate"], 2), True), ("drift [km]", lambda r: f(r["drift_km"], 0), True),
            ("superpressure at top [Pa]", lambda r: f(r["dp_top"], 0), True), ("vented [kg]", lambda r: f(r["vented_kg"]), True)]))
        w("\n![ascent](ascent.png)\n")

    for data, title, img in ((sw_, "Payload and altitude sensitivity", "sweeps.png"), (sens, "Sensitivity to the estimates", "sensitivity.png"),
                             (par, "Pareto fronts", "pareto.png"), (sea, "Seasonal operation at European latitudes", "seasons.png"),
                             (con, "Structural and thermal constraints", "constraints.png"), (atm, "Atmosphere", "atmosphere.png"),
                             (wind, "Winds", "wind.png")):
        if data:
            w(f"## {title}\n")
            if data is par:
                w(f"{par['n']} Sobol designs of the reference ship, {par['n_feasible']} pass the gate, {par['n_meets']} meet the summer scenario. "
                  "Fronts are drawn over the feasible set.\n")
            if data is atm:
                w(f"The troposphere-only `og.atmosphere` is {f(abs(atm['isa_error_at_20km']) * 100, 1)} % off in density at 20 km; "
                  "the studies use `og.stratosphere`.\n")
            if data is sea:
                w(sea.get("note", "") + "\n")
            w(f"![{title}]({img})\n")
    w("## What is verified and what is estimated\n")
    w(table(VERIFIED, [("model", lambda r: r[0], False), ("where", lambda r: f"`{r[1]}`", False), ("status", lambda r: r[2], False)]))
    p = out / "report.md"
    p.write_text("\n".join(L) + "\n")
    return p


def _mass(fam, L, group):
    r = fam["summer"].get(L, {}).get("best", {})
    return r.get("masses", {}).get(group)
